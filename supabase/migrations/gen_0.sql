CREATE OR REPLACE FUNCTION public.update_player_username(p_new_username TEXT)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_user_id UUID;
    v_existing TEXT;
BEGIN
    v_user_id := auth.uid();
    
    IF p_new_username IS NULL OR length(p_new_username) < 3 OR length(p_new_username) > 16 THEN
        RETURN json_build_object('success', false, 'error', 'Username must be between 3 and 16 characters');
    END IF;
    
    IF p_new_username !~ '^[a-zA-Z0-9_]+$' THEN
        RETURN json_build_object('success', false, 'error', 'Username can only contain letters, numbers, and underscores');
    END IF;
    
    SELECT username INTO v_existing FROM public.players 
    WHERE username = p_new_username AND id != v_user_id;
    
    IF v_existing IS NOT NULL THEN
        RETURN json_build_object('success', false, 'error', 'Username already taken');
    END IF;
    
    UPDATE public.players
    SET username = p_new_username, updated_at = now()
    WHERE id = v_user_id;
    
    RETURN json_build_object('success', true, 'username', p_new_username);
END;
$$;

CREATE OR REPLACE FUNCTION public.choose_player_sect(p_sect_id TEXT)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_user_id UUID;
    v_sect_exists BOOLEAN;
BEGIN
    v_user_id := auth.uid();
    
    SELECT EXISTS(SELECT 1 FROM public.sects WHERE id = p_sect_id) INTO v_sect_exists;
    
    IF NOT v_sect_exists THEN
        RETURN json_build_object('success', false, 'error', 'Invalid sect ID');
    END IF;
    
    UPDATE public.players
    SET sect_id = p_sect_id, updated_at = now()
    WHERE id = v_user_id;
    
    RETURN json_build_object('success', true, 'sect_id', p_sect_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.complete_player_onboarding()
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_user_id UUID;
    v_username TEXT;
    v_sect_id TEXT;
BEGIN
    v_user_id := auth.uid();
    
    SELECT username, sect_id INTO v_username, v_sect_id 
    FROM public.players WHERE id = v_user_id;
    
    IF v_username IS NULL OR v_username = '' THEN
        RETURN json_build_object('success', false, 'error', 'Username not set');
    END IF;
    
    IF v_sect_id IS NULL OR v_sect_id = '' THEN
        RETURN json_build_object('success', false, 'error', 'Sect not chosen');
    END IF;
    
    UPDATE public.players
    SET onboarding_complete = true, updated_at = now()
    WHERE id = v_user_id;
    
    RETURN json_build_object('success', true, 'onboarding_complete', true);
END;
$$;

CREATE OR REPLACE FUNCTION public.get_player_status()
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_user_id UUID;
    v_result JSON;
BEGIN
    v_user_id := auth.uid();
    
    SELECT json_build_object(
        'id', p.id,
        'username', p.username,
        'ip_address', p.ip_address,
        'sect_id', p.sect_id,
        'sect_name', s.name,
        'sect_emoji', s.emoji,
        'onboarding_complete', p.onboarding_complete
    ) INTO v_result
    FROM public.players p
    LEFT JOIN public.sects s ON p.sect_id = s.id
    WHERE p.id = v_user_id;
    
    RETURN COALESCE(v_result, json_build_object('error', 'Player not found'));
END;
$$;

CREATE OR REPLACE FUNCTION public.get_available_sects()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    RETURN (
        SELECT jsonb_agg(
            jsonb_build_object(
                'id', s.id,
                'name', s.name,
                'ip_address', s.ip_address,
                'emoji', s.emoji,
                'description', s.description,
                'principles', s.principles,
                'tone_description', s.tone_description
            )
            ORDER BY s.display_order ASC
        )
        FROM public.sects s
    );
END;
$$;


-- ==========================================
-- 1. MASTER NETWORK REGISTRY & UTILITIES
-- ==========================================

CREATE TABLE IF NOT EXISTS public.network_addresses (
    ip_address inet PRIMARY KEY,
    entity_type TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

COMMENT ON TABLE public.network_addresses IS 'Master registry of all IP addresses to prevent cross-entity collisions.';
COMMENT ON COLUMN public.network_addresses.entity_type IS 'Table of entity owning the IP (e.g., players, sects, bots, etc)';

CREATE OR REPLACE FUNCTION public.allocate_network_address(p_entity_type TEXT) 
RETURNS inet AS $$
DECLARE
    candidate_ip inet;
BEGIN
    LOOP
        candidate_ip := (
            floor(random() * 254 + 1)::text || '.' ||
            floor(random() * 254 + 1)::text || '.' ||
            floor(random() * 254 + 1)::text || '.' ||
            floor(random() * 254 + 1)::text
        )::inet;

        BEGIN
            INSERT INTO public.network_addresses (ip_address, entity_type)
            VALUES (candidate_ip, p_entity_type);
            
            RETURN candidate_ip;
        EXCEPTION WHEN unique_violation THEN
            -- Collision detected, loop continues to try a new IP
        END;
    END LOOP;
END;
$$ LANGUAGE plpgsql VOLATILE SECURITY DEFINER;

-- ==========================================
-- 2. CORE TABLES
-- ==========================================

CREATE TABLE IF NOT EXISTS public.sects (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    ip_address inet UNIQUE REFERENCES public.network_addresses(ip_address) ON DELETE SET NULL,
    emoji TEXT NOT NULL,
    description TEXT,
    principles TEXT[] NOT NULL DEFAULT '{}',
    tone_description TEXT,
    display_order INT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

COMMENT ON TABLE public.sects IS 'Faction metadata that drives AI generation and game rules. Read-only for players.';
COMMENT ON COLUMN public.sects.id IS 'Slug identifier: gilded_path, holy_way, final_watch, black_tribunal';
COMMENT ON COLUMN public.sects.principles IS 'Array of faction principles used for AI prompts';

CREATE TABLE IF NOT EXISTS public.players (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT UNIQUE,
    ip_address inet UNIQUE NOT NULL DEFAULT public.allocate_network_address('players'),
    sect_id TEXT REFERENCES public.sects(id) ON DELETE SET NULL,
    onboarding_complete BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),
    
    CONSTRAINT players_username_check CHECK (
        username IS NULL OR (
            length(username) >= 3 AND 
            length(username) <= 16 AND 
            username ~ '^[a-zA-Z0-9_]+$'
        )
    )
);

COMMENT ON TABLE public.players IS 'Core player data. Tracks identity, network location, and faction.';
COMMENT ON COLUMN public.players.ip_address IS 'The unique network identifier used for in-game routing and attacks.';

-- ==========================================
